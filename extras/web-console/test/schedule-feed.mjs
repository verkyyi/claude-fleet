import assert from 'node:assert/strict';
import { ScheduleReader } from '../src/app/schedule-feed.ts';
let navigations=0, calls=0, reply=()=>Promise.resolve(new Response(JSON.stringify({value:'private'}),{status:200}));
globalThis.location={assign(){navigations++}};
globalThis.fetch=()=>{calls++;return reply()};
const reader=new ScheduleReader();
assert.deepEqual(await reader.read('/v1/schedules'),{kind:'ok',data:{value:'private'}});
let late;
reply=()=>new Promise(resolve=>late=resolve);
const pending=reader.read('/v1/schedules');
reply=()=>Promise.resolve(new Response('',{status:401}));
assert.deepEqual(await reader.read('/v1/schedules'),{kind:'expired'});
late(new Response(JSON.stringify({value:'stale private'}),{status:200}));
assert.deepEqual(await pending,{kind:'expired'});
const before=calls;
assert.deepEqual(await reader.read('/v1/schedules'),{kind:'expired'});
assert.equal(calls,before,'expired background reader must not poll again');
assert.equal(navigations,0,'background reads must not tear down a conversation');
const retry=new ScheduleReader();
reply=()=>Promise.reject(Error('network'));
assert.deepEqual(await retry.read('/v1/schedules'),{kind:'error'});
reply=()=>Promise.resolve(new Response('{"value":"restored"}',{status:200}));
assert.deepEqual(await retry.read('/v1/schedules'),{kind:'ok',data:{value:'restored'}});
console.log('PASS schedule feed: expiry, late response fence, stopped polling, no navigation and network recovery');
