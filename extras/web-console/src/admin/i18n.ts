// the review page (demo.ts) picks its language from its frame
const demoLang = (window as any).__DEMO_LANG as Lang | undefined;
export const lang: Lang = demoLang || sharedLang;
if (demoLang) document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";

export function t(key: MsgKey, vars: Record<string, string | number> = {}): string {
  const s = (lang === "en" ? en : zh)[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}

// ago is how long ago iso was, in words; "" for never.
export function ago(iso: string | undefined, now = Date.now()): string {
  if (!iso || iso.startsWith("0001-")) return "";
  const s = Math.max(0, (now - Date.parse(iso)) / 1000);
  if (s < 60) return t("seen.now");
  if (s < 3600) return t("seen.min", { n: Math.floor(s / 60) });
  if (s < 86400) return t("seen.hour", { n: Math.floor(s / 3600) });
  return t("seen.day", { n: Math.floor(s / 86400) });
}

export function when(iso: string | undefined): string {
  if (!iso || iso.startsWith("0001-")) return "—";
  return new Date(iso).toLocaleString(lang === "zh" ? "zh-CN" : "en", { dateStyle: "medium", timeStyle: "short" });
}

// inTime is how long until iso, in words; "" when past or unknown.
export function inTime(iso: string | number | null | undefined, now = Date.now()): string {
  const ms = typeof iso === "number" ? iso : Date.parse(String(iso || ""));
  if (!Number.isFinite(ms) || ms <= now) return "";
  const m = Math.round((ms - now) / 60000);
  if (m < 60) return t("in.m", { m: Math.max(1, m) });
  if (m < 48 * 60) return t("in.hm", { h: Math.floor(m / 60), m: m % 60 });
  return t("in.d", { d: Math.round(m / 1440) });
}
