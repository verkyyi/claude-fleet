#!/bin/bash
# fleet-connect-route-selftest.sh — `fleet connect` picks its own route
# (issue #1414): bin/fleet-connect.py through the bin/fleet dispatcher, against
# a fake hub (stdlib python3 on 127.0.0.1) that serves /v1/fleet/routes and the
# relay, plus a fake sshd that only says its banner. No real hub, sshd or
# network beyond loopback.
#
# Legs: rank_routes orders by handshakes answered, then median latency, then
# the hub's order; the `fleet login` ssh-config snippet parses back into
# routes; with three routes (tailnet · public · relay) and two of them dark
# the live one is chosen and the --verbose table shows all three; a fresh
# remembered choice is re-checked with one handshake and used without asking
# the hub again; closing the remembered route moves the next run onto another
# (the relay, as a ProxyCommand back into this script); an expired cache asks
# the hub again; a certificate signs the route-list request (checked with
# `ssh-keygen -Y check-novalidate`); the hub unreachable → the snippet's
# routes; an unknown machine exits 1 naming the ones there are.
set -uo pipefail
BIN="$(cd "$(dirname "$0")" && pwd)"
WORK=$(mktemp -d "${TMPDIR:-/tmp}/fleet-connect-route-selftest.XXXXXX") || exit 2
HUB_PID=""
cleanup() {
  if [ -n "$HUB_PID" ]; then kill "$HUB_PID" 2>/dev/null; fi
  rm -rf "${WORK:?}"
}
trap cleanup EXIT INT TERM HUP
export HOME="$WORK/home" XDG_CONFIG_HOME="$WORK/home/.config" XDG_CACHE_HOME="$WORK/home/.cache"
mkdir -p "$HOME/.ssh"
unset FLEET_HUB_URL FLEET_HUB_TOKEN FLEET_CERT FLEET_CONNECT_CACHE_SECS
export FLEET_CONNECT_TIMEOUT=2 FLEET_CONNECT_PROBES=3

fail=0
ok()  { echo "ok   $*"; }
bad() { echo "FAIL $*"; fail=1; }

# ── 1 — ranking + snippet parsing, as functions ─────────────────────────────
out=$(python3 - "$BIN/fleet-connect.py" <<'EOF'
import importlib.util, sys
spec = importlib.util.spec_from_file_location("fc", sys.argv[1]); fc = importlib.util.module_from_spec(spec); spec.loader.exec_module(fc)
rows = [
  {"name": "fast-flaky", "ms": [10, 12], "order": 0},
  {"name": "dead",       "ms": [],       "order": 1},
  {"name": "slow-solid", "ms": [90, 80, 85], "order": 2},
  {"name": "fast-solid", "ms": [30, 20, 25], "order": 3},
  {"name": "tie-later",  "ms": [20, 30, 25], "order": 4},
]
print(",".join(r["name"] for r in fc.rank_routes(rows)))
snip = """# fleet-ssh-config v1 — generated by the fleet hub
Host m4 fleet-m4 fleet-m4-public
  HostName gw.example.com
  Port 22023
  User alice
  IdentityFile ~/.ssh/fleet-cert
Host fleet-m4-tailnet
  HostName m4.tail.ts.net
  User alice
Host m-5 fleet-m-5 fleet-m-5-lan
  HostName 10.0.0.5
"""
info = fc.parse_ssh_config_snippet(snip)
print(info["login"], ";".join("%s:%s" % (m["alias"], ",".join("%s=%s:%s" % (r["name"], r["host"], r["port"]) for r in m["routes"])) for m in info["machines"]))
EOF
)
want_rank="fast-solid,tie-later,slow-solid,fast-flaky,dead"
want_snip="alice m4:public=gw.example.com:22023,tailnet=m4.tail.ts.net:0;m-5:lan=10.0.0.5:0"
[ "$(sed -n 1p <<<"$out")" = "$want_rank" ] && ok "rank: answered first, then median, then hub order" \
  || bad "rank: got $(sed -n 1p <<<"$out") want $want_rank"
[ "$(sed -n 2p <<<"$out")" = "$want_snip" ] && ok "snippet: fleet login's ssh config parses back into routes" \
  || bad "snippet: got $(sed -n 2p <<<"$out") want $want_snip"

# ── the fake hub + fake sshd ────────────────────────────────────────────────
# $WORK/state (JSON, re-read on every request): tailnet_up, relay_ok, down.
cat > "$WORK/hub.py" <<'EOF'
import base64, hashlib, json, os, socket, struct, subprocess, sys, tempfile, threading, urllib.parse
W = sys.argv[1]
def state():
    try: return json.load(open(W + "/state"))
    except Exception: return {}
def bump(name):
    p = W + "/" + name
    n = int(open(p).read()) if os.path.exists(p) else 0
    open(p, "w").write(str(n + 1))

def listener():
    s = socket.socket(); s.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
    s.bind(("127.0.0.1", 0)); s.listen(16); return s

# The fake sshd: a banner, or (tailnet_up false) a close with nothing said.
sshd = listener()
def serve_sshd():
    while True:
        c, _ = sshd.accept()
        if state().get("tailnet_up", True):
            c.sendall(b"SSH-2.0-fake_sshd\r\n")
        c.close()
threading.Thread(target=serve_sshd, daemon=True).start()
open(W + "/sshd_port", "w").write(str(sshd.getsockname()[1]))
# A port nothing listens on: bound, then closed.
d = listener(); dead = d.getsockname()[1]; d.close()

def send(c, op, data):
    n = len(data); h = bytes([0x80 | op])
    h += bytes([n]) if n < 126 else bytes([126]) + struct.pack("!H", n)
    c.sendall(h + data)

def recv(c, buf):
    def rx(n):
        while len(buf[0]) < n:
            d = c.recv(65536)
            if not d: raise EOFError
            buf[0] += d
        out, buf[0] = buf[0][:n], buf[0][n:]; return out
    b0, b1 = rx(2); n = b1 & 0x7F
    if n == 126: n = struct.unpack("!H", rx(2))[0]
    mask = rx(4) if b1 & 0x80 else b"\0\0\0\0"
    return b0 & 0x0F, bytes(x ^ mask[i % 4] for i, x in enumerate(rx(n)))

def reply(c, code, obj):
    body = json.dumps(obj).encode()
    c.sendall(b"HTTP/1.1 %d X\r\nContent-Type: application/json\r\nContent-Length: %d\r\nConnection: close\r\n\r\n" % (code, len(body)) + body)
    c.close()

def serve(c):
    buf = [b""]
    while b"\r\n\r\n" not in buf[0]:
        d = c.recv(4096)
        if not d: return c.close()
        buf[0] += d
    head, buf[0] = buf[0].split(b"\r\n\r\n", 1)
    lines = head.decode().split("\r\n")
    method, path = lines[0].split(" ")[:2]
    hdr = {k.lower(): v for k, v in (l.split(": ", 1) for l in lines[1:])}
    st = state()
    if st.get("down"):
        return reply(c, 503, {"error": "hub down"})
    u = urllib.parse.urlsplit(path)
    if u.path == "/v1/fleet/routes":
        bump("routes_hits")
        if hdr.get("authorization") != "Bearer tok-1":
            n = int(hdr.get("content-length", "0"))
            while len(buf[0]) < n: buf[0] += c.recv(4096)
            m = json.loads(buf[0][:n] or b"{}")
            with tempfile.TemporaryDirectory() as td:
                open(td + "/sig", "w").write(m.get("sig", ""))
                r = subprocess.run(["ssh-keygen", "-Y", "check-novalidate", "-n", "fleet-routes@claude-fleet", "-s", td + "/sig"],
                                   input=("fleet-routes %d" % m.get("ts", 0)).encode(), capture_output=True)
            if method != "POST" or r.returncode != 0 or "-cert-v01@openssh.com" not in m.get("cert", ""):
                return reply(c, 401, {"error": "bad cert"})
            open(W + "/certok", "w").write("ok")
        return reply(c, 200, {"hub": "x", "login": "alice", "machines": [
            {"hostname": "mini", "alias": "m4", "relay": True, "routes": [
                {"name": "tailnet", "host": "127.0.0.1", "port": sshd.getsockname()[1]},
                {"name": "public", "host": "127.0.0.1", "port": dead}]},
            {"hostname": "macmini", "alias": "m5", "relay": False, "routes": [
                {"name": "public", "host": "127.0.0.1", "port": dead}]}]})
    if u.path == "/v1/ssh-relay/connect":
        bump("relay_hits")
        acc = base64.b64encode(hashlib.sha1((hdr["sec-websocket-key"] + "258EAFA5-E914-47DA-95CA-C5AB0DC85B11").encode()).digest()).decode()
        c.sendall(("HTTP/1.1 101 Switching Protocols\r\nUpgrade: websocket\r\nConnection: Upgrade\r\nSec-WebSocket-Accept: %s\r\n\r\n" % acc).encode())
        if not st.get("relay_ok"):
            send(c, 1, json.dumps({"type": "error", "code": "NODE_OFFLINE", "message": "no agent on mini"}).encode())
            return c.close()
        send(c, 1, json.dumps({"type": "ready"}).encode())
        send(c, 2, b"SSH-2.0-fake_relay\r\n")
        try:
            while True:
                op, _ = recv(c, buf)
                if op == 8: break
        except (EOFError, OSError):
            pass
        return c.close()
    reply(c, 404, {"error": "no"})

hub = listener()
open(W + "/port.tmp", "w").write(str(hub.getsockname()[1])); os.rename(W + "/port.tmp", W + "/port")
while True:
    c, _ = hub.accept()
    threading.Thread(target=serve, args=(c,), daemon=True).start()
EOF
echo '{"tailnet_up": true, "relay_ok": false}' > "$WORK/state"
python3 "$WORK/hub.py" "$WORK" &
HUB_PID=$!
for _ in $(seq 1 50); do [ -s "$WORK/port" ] && break; sleep 0.1; done
PORT=$(cat "$WORK/port" 2>/dev/null)
[ -n "$PORT" ] || { echo "FAIL fake hub did not start"; exit 1; }
HUB="http://127.0.0.1:$PORT"
hits() { cat "$WORK/$1" 2>/dev/null || echo 0; }

# ── 2 — three routes, two dark: the live one, and the table shows all three ─
out=$(FLEET_HUB_TOKEN=tok-1 "$BIN/fleet" connect --hub "$HUB" --verbose --print 2>"$WORK/err2"); rc=$?
tbl=$(cat "$WORK/err2")
if [ "$rc" = 0 ] && [[ "$out" == *"HostKeyAlias=fleet-m4"* ]] && [[ "$out" == *" -l alice "* ]] \
   && [[ "$out" != *ProxyCommand* ]] && [[ "$tbl" == *"* tailnet"*"3/3"* ]] \
   && [[ "$tbl" == *"public"*"0/3"* ]] && [[ "$tbl" == *"relay"*"0/3"*NODE_OFFLINE* ]] && [[ "$tbl" == *"选中 tailnet"* ]]; then
  ok "two of three dark: tailnet chosen, table lists tailnet/public/relay"
  sed 's/^/       /' <<<"$tbl"
else bad "three routes: rc=$rc out=$out"$'\n'"$tbl"; fi

# ── 3 — fresh cache: one re-check handshake, the hub's list not asked again ─
before=$(hits routes_hits)
out=$(FLEET_HUB_TOKEN=tok-1 "$BIN/fleet" connect --hub "$HUB" --verbose --print 2>"$WORK/err3"); rc=$?
if [ "$rc" = 0 ] && [ "$(hits routes_hits)" = "$before" ] && grep -q '秒前测出的 tailnet' "$WORK/err3" && [[ "$out" != *ProxyCommand* ]]; then
  ok "fresh cache: re-checked tailnet with one handshake, no route-list fetch"
else bad "cache reuse: rc=$rc hits $before→$(hits routes_hits) $(cat "$WORK/err3")"; fi

# ── 4 — close the remembered line: the next run moves to the relay ─────────
echo '{"tailnet_up": false, "relay_ok": true}' > "$WORK/state"
out=$(FLEET_HUB_TOKEN=tok-1 "$BIN/fleet" connect --hub "$HUB" --verbose --print 2>"$WORK/err4"); rc=$?
if [ "$rc" = 0 ] && grep -q '不通了' "$WORK/err4" && grep -q '选中 relay' "$WORK/err4" \
   && [[ "$out" == *"ProxyCommand="*"fleet-connect.py --proxy mini --hub $HUB"* ]] && [[ "$out" == *" m4" ]]; then
  ok "remembered route closed: re-measured, relay chosen (ProxyCommand --proxy mini)"
else bad "failover: rc=$rc out=$out"$'\n'"$(cat "$WORK/err4")"; fi

# ── 5 — an expired cache asks the hub again ─────────────────────────────────
echo '{"tailnet_up": true, "relay_ok": true}' > "$WORK/state"
before=$(hits routes_hits)
FLEET_CONNECT_CACHE_SECS=0 FLEET_HUB_TOKEN=tok-1 "$BIN/fleet" connect --hub "$HUB" --print >/dev/null 2>"$WORK/err5"; rc=$?
[ "$rc" = 0 ] && [ "$(hits routes_hits)" = $((before + 1)) ] && ok "expired cache: route list fetched and measured again" \
  || bad "expiry: rc=$rc hits $before→$(hits routes_hits) $(cat "$WORK/err5")"

# ── 6 — a certificate signs the route-list request; hub.json gives the URL ──
if command -v ssh-keygen >/dev/null 2>&1; then
  ssh-keygen -q -t ed25519 -N '' -f "$WORK/ca" >/dev/null
  ssh-keygen -q -t ed25519 -N '' -f "$HOME/.ssh/fleet-cert" >/dev/null
  ssh-keygen -q -s "$WORK/ca" -I wecom:wx-alice -n alice -V +1h "$HOME/.ssh/fleet-cert.pub" >/dev/null 2>&1
  mkdir -p "$XDG_CONFIG_HOME/claude-fleet"
  printf '{"url": "%s"}\n' "$HUB" > "$XDG_CONFIG_HOME/claude-fleet/hub.json"
  out=$("$BIN/fleet" connect m4 --retest --print 2>"$WORK/err6"); rc=$?
  if [ "$rc" = 0 ] && [ -s "$WORK/certok" ] && [[ "$out" == *"CertificateFile=$HOME/.ssh/fleet-cert-cert.pub"* ]]; then
    ok "certificate: route list fetched with a signed timestamp; ssh gets the cert"
  else bad "certificate: rc=$rc out=$out $(cat "$WORK/err6")"; fi
else
  echo "skip certificate leg: no ssh-keygen"
fi

# ── 7 — the hub unreachable: the snippet `fleet login` wrote ────────────────
SSHD_PORT=$(cat "$WORK/sshd_port")
cat > "$HOME/.ssh/fleet-ssh-config" <<EOF
# fleet-ssh-config v1 — generated by the fleet hub
Host m4 fleet-m4 fleet-m4-tailnet
  HostName 127.0.0.1
  Port ${SSHD_PORT:-1}
  User alice
EOF
echo '{"down": true}' > "$WORK/state"
out=$(FLEET_HUB_TOKEN=tok-1 "$BIN/fleet" connect --hub "$HUB" --retest --verbose --print 2>"$WORK/err7"); rc=$?
if [ "$rc" = 0 ] && grep -q 'fleet-ssh-config' "$WORK/err7" && [[ "$out" == *"-p $SSHD_PORT 127.0.0.1"* ]]; then
  ok "hub down: routes from ~/.ssh/fleet-ssh-config"
else bad "snippet fallback: rc=$rc out=$out $(cat "$WORK/err7")"; fi
echo '{"tailnet_up": true}' > "$WORK/state"

# ── 8 — an unknown machine exits 1 and names the ones there are ─────────────
out=$(FLEET_HUB_TOKEN=tok-1 "$BIN/fleet" connect --hub "$HUB" nosuch --print 2>&1); rc=$?
case "$rc:$out" in
  1:*nosuch*m4*m5*) ok "unknown machine: exit 1, lists m4 m5" ;;
  *) bad "unknown machine: rc=$rc out=$out" ;;
esac

[ "$fail" = 0 ] && echo "PASS fleet-connect-route-selftest" || echo "FAIL fleet-connect-route-selftest"
exit "$fail"
